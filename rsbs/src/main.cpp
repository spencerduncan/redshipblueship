extern "C" {
// Records an archive path in MM's archive-origin registry (RecordMMArchivePath,
// games/mm/2s2h/GameExports_SingleExe.cpp) — the predicate the per-archive
// Room/Cutscene/Path/Array dispatcher and ResourceMgr_ListFilesForGame key on.
// Declared here rather than included: that TU's headers are not on this
// target's include path.
void MM_RecordArchivePath(const char* path);
}

static const char* ArchiveAppName(GameId game) {
    switch (game) {
        case GAME_OOT:
            return "soh";
        case GAME_MM:
            return "2s2h";
        default:
            return nullptr;
    }
}

// #577 M1: the curated cross-game archive a game DRAWS from, named for that
// game (its host): redship-oot.o2r carries MM-origin models for OoT,
// redship-mm.o2r OoT-origin models for MM. Both are generated by
// GenerateRedshipOtr (scripts/make_redship_otr.py) from
// assets/crossgame/manifest.txt, whose direction column picks the half.
static const char* CuratedArchiveName(GameId host) {
    switch (host) {
        case GAME_OOT:
            return "redship-oot.o2r";
        case GAME_MM:
            return "redship-mm.o2r";
        default:
            return nullptr;
    }
}

// Mount @p host's curated half with @p host's identity.
//
// IDENTITY IS BEHAVIOUR here, not a label. RsbsMMArchiveFactoryDispatcher
// parses Room/Cutscene/Path/Array resources with MM's reader exactly when the
// OWNING archive is recorded as MM's, and ResourceMgr_ListFilesForGame files a
// path under the game its owner belongs to. So the MM half is recorded through
// MM's own registry — BEFORE it is added, so no load can observe it mounted
// but unrecorded — and the OoT half is simply not recorded, which is what makes
// an archive OoT's.
//
// Called right after the host's base archives and before its mods (see the
// callers): the curated paths are absent from the host's base archives by
// construction (the generator refuses a collision with any of them --
// oot.o2r, soh.o2r and, when extracted, oot-mq.o2r for OoT; mm.o2r and
// 2ship.o2r for MM -- as they stood at generation time), so their relative order
// does not matter, but a player's mod must still be able to restyle a foreign
// model, so mods stay last. The source game's own base archive wins those
// same paths back whenever the source game is the one arriving, because every
// switch re-adds the arriving game's base archives — so a curated path is
// always owned by an archive of the RUNNING game's identity.
//
// Absent is normal (a tree that never ran GenerateRedshipOtr, or a packaged
// build — see #806): foreign models then fall back to their model-less
// stand-ins, exactly as before #577.
static void MountCuratedArchive(Ship::ArchiveManager& archiveManager, GameId host) {
    const char* name = CuratedArchiveName(host);
    const char* appName = ArchiveAppName(host);
    if (name == nullptr || appName == nullptr) {
        return;
    }
    const std::string path = Ship::Context::LocateFileAcrossAppDirs(name, appName);
    if (path.empty() || !std::filesystem::exists(path)) {
        return;
    }

    if (host == GAME_MM) {
        MM_RecordArchivePath(path.c_str());
    }
    if (archiveManager.AddArchive(path)) {
        printf("[RSBS] Cross-game archive ready (%s identity): %s\n", Game_ToString(host), path.c_str());
    } else {
        fprintf(stderr, "[RSBS] Warning: failed to load cross-game archive %s; foreign models in %s keep their "
                        "model-less stand-ins\n",
                path.c_str(), Game_ToString(host));
    }
}

static void ReapplyModArchives(Ship::ArchiveManager& archiveManager, GameId targetGame);

// Not static: declared in src/common/mod_archives.h so the #593 lock
// (src/common/tests/test_curated_archive_order.c) can drive THIS function
// rather than a copy of it.
extern "C" void Combo_EnsureGameArchivesLoaded(GameId targetGame) {
    auto ctx = Ship::Context::GetInstance();
    if (!ctx || !ctx->GetResourceManager()) return;
    auto archiveManager = ctx->GetResourceManager()->GetArchiveManager();
    if (!archiveManager) return;

    struct ArchiveEntry { const char* filename; bool useLocate; };
    const char* appName = ArchiveAppName(targetGame);
    std::vector<ArchiveEntry> entries;

    switch (targetGame) {
        case GAME_OOT:
            entries = {{"oot.o2r", true}, {"oot-mq.o2r", true}, {"soh.o2r", false}};
            break;
        case GAME_MM:
            entries = {{"mm.o2r", true}, {"2ship.o2r", false}};
            break;
        default:
            return;
    }

    for (const auto& entry : entries) {
        std::string path = entry.useLocate
            ? Ship::Context::LocateFileAcrossAppDirs(entry.filename, appName)
            : Ship::Context::GetPathRelativeToAppBundle(entry.filename);

        if (path.empty() || !std::filesystem::exists(path)) continue;

        auto archive = archiveManager->AddArchive(path);
        if (archive) {
            printf("[RSBS] Archive ready: %s\n", path.c_str());
        } else {
            fprintf(stderr, "[RSBS] Warning: Failed to load archive: %s\n", path.c_str());
        }
    }

    // #577 M1: the arriving game's curated cross-game half, after its base
    // archives and before its mods.
    MountCuratedArchive(*archiveManager, targetGame);

    ReapplyModArchives(*archiveManager, targetGame);
}

// The boot half of the above: the booted game's own Init has already mounted
// its base archives and mods, so this adds the curated half and puts the mods
// back on top of it (declared in src/common/mod_archives.h).
extern "C" void Combo_MountCuratedArchive(GameId host) {
    auto ctx = Ship::Context::GetInstance();
    if (!ctx || !ctx->GetResourceManager()) return;
    auto archiveManager = ctx->GetResourceManager()->GetArchiveManager();
    if (!archiveManager) return;

    MountCuratedArchive(*archiveManager, host);
    ReapplyModArchives(*archiveManager, host);
}

static void ReapplyModArchives(Ship::ArchiveManager& archiveManager, GameId targetGame) {
    // #593: put the target game's mod archives back on top.
    //
    // ArchiveManager resolution is last-added-wins with no priority field
    // (ArchiveManager::AddArchive overwrites mFileToArchive[hash]
    // unconditionally), and that is the ONLY mechanism by which a user mod
    // overrides a base asset: both ports mount mods/ AFTER their base
    // archives. The base re-add above — which #154 requires — therefore puts
    // the base archives back on top and silently revokes every mod override.
    // OoT feels it on the first return trip (it mounts mods late, at GUI init)
    // and MM on its second arrival. Re-apply here so the post-switch mount
    // order matches the post-boot one.
    //
    // Only the TARGET game's mods: the base archives just re-added are the
    // target's, so the target's mods are exactly what got clobbered. The other
    // game's mods are still mounted above ITS base archives and are untouched.
    //
    // The registry (src/common/mod_archives.h) is fed by each port at mount
    // time, so this replays the player's ACTUAL enabled set in the player's
    // ACTUAL order. Re-globbing mods/ here would instead resurrect archives the
    // player disabled.
    //
    // Also run at boot by Combo_MountCuratedArchive, after the curated half, so
    // the mods sit above it there too (#577 M1).
    const int modCount = Combo_GetModArchiveCount(targetGame);
    for (int i = 0; i < modCount; i++) {
        const char* modPath = Combo_GetModArchive(targetGame, i);
        if (modPath == nullptr || modPath[0] == '\0') continue;

        if (!std::filesystem::exists(modPath)) {
            fprintf(stderr,
                    "[RSBS] WARNING: mod archive is gone since it was mounted, so its overrides are NOT active "
                    "after this switch: %s\n",
                    modPath);
            continue;
        }

        // #705: a registered mod can be a loose asset FOLDER, and re-adding one
        // re-walks it with libultraship's throwing directory iterator. A folder
        // that became unreadable since boot must cost that one mod, not the switch.
        std::shared_ptr<Ship::Archive> reapplied;
        try {
            reapplied = archiveManager.AddArchive(std::string(modPath));
        } catch (const std::exception& e) {
            fprintf(stderr, "[RSBS] WARNING: re-applying mod %s threw (%s)\n", modPath, e.what());
        }
        if (reapplied) {
            printf("[RSBS] Mod archive re-applied over %s base archives: %s\n", Game_ToString(targetGame), modPath);
        } else {
            // Loud on purpose. Silence here is the whole bug: the mod stays
            // listed as enabled in the menu while none of its assets apply.
            fprintf(stderr,
                    "[RSBS] WARNING: failed to re-apply mod archive after the switch; the base archives now "
                    "override it and this mod will NOT apply: %s\n",
                    modPath);
        }
    }
}

