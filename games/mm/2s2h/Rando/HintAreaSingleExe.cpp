/** RandoCheckId -> MM area, built once from MM's own check table on first use. */
const std::array<uint8_t, RC_MAX>& MmAreaTable() {
    static const std::array<uint8_t, RC_MAX> table = [] {
        std::array<uint8_t, RC_MAX> t{};
        for (const auto& [id, row] : Rando::StaticData::Checks) {
            if (id > RC_UNKNOWN && id < RC_MAX) {
                t[id] = MmSceneDefaultArea(row.sceneId);
            }
        }
        for (const MmAreaOverride& o : kMmAreaOverrides) {
            t[o.check] = o.area;
        }
        return t;
    }();
    return table;
}

uint8_t MmAreaOfCheck(uint16_t check) {
    if (check <= RC_UNKNOWN || check >= RC_MAX) {
        return COMBO_AREA_NONE;
    }
    return MmAreaTable()[check];
}

const ComboAreaAdapter kMmAreaAdapter = { MmAreaOfCheck };

/** The describer's registrar shape (ComboLogicEngineSingleExe.cpp): stores a
 *  pointer, calls nothing. 2ship_rando links WHOLE_ARCHIVE, so it survives. */
struct MmAreaAdapterRegistrar {
    MmAreaAdapterRegistrar() {
        Combo_RegisterAreaAdapter((uint8_t)GAME_MM, &kMmAreaAdapter);
    }
};
const MmAreaAdapterRegistrar gMmAreaAdapterRegistrar;

