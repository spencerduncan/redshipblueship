/** One row of MM's check table, without MM's enums in src/common: returns 1 when
 *  `id` names a real row other than RC_UNKNOWN, 0 otherwise, and reports whether
 *  the row is an enemy drop (the one class OoTMM gives no region). */
extern "C" int MM_HintArea_TestCheckRow(uint16_t id, int* outIsEnemyDrop) {
    const auto it = Rando::StaticData::Checks.find((RandoCheckId)id);
    if (it == Rando::StaticData::Checks.end() || it->second.randoCheckId == RC_UNKNOWN) {
        return 0;
    }
    if (outIsEnemyDrop != nullptr) {
        *outIsEnemyDrop = (it->second.randoCheckType == RCTYPE_ENEMY_DROP) ? 1 : 0;
    }
    return 1;
}

