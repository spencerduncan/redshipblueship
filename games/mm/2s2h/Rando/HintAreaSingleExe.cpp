/**
 * @file HintAreaSingleExe.cpp
 * @brief MM's half of the shared area vocabulary (epic #575, child H1).
 *
 * Maps every MM check (RandoCheckId) into the MM half of src/common's area
 * vocabulary (combo_area.h) and registers that mapping as MM's area adapter.
 * ADR 0002: MM's own ids are read only here; what crosses into src/common is
 * the {GAME_MM, area} pair.
 *
 * The answer is OoTMM's region for the check (OoTMM's data/world/mm/**, read
 * read-only: `region:` names a region, `dungeon:` maps through DUNGEONS_REGIONS,
 * `region: ENTRANCE` / BUFFER take the region of the area that leads in), with
 * OoTMM's extraHintRegions granularity, so the Butler Race, the Goron Racetrack
 * and the inverted Stone Tower Temple are their own areas and every one of the
 * 46 MM areas holds checks. It is stored as a scene default plus a per-check
 * override list. The table was derived by a script over OoTMM's world and check
 * files; the 636 2ship rows whose names match an OoTMM location by name all
 * agree with OoTMM's region (PR for #575 H1). OoTMM gives the 55 enemy drops no
 * region (packages/logic/src/hints.ts ignores region-less checks), so they are
 * COMBO_AREA_NONE, as is RC_UNKNOWN.
 *
 * Nothing here is persisted: the table is a pure function of the check id, so
 * no save or golden carries it.
 *
 * Child H2 adds what MM's own hints say with it (Rando/HintArea.h): the area's
 * name and preposition in place of the scene name.
 */

