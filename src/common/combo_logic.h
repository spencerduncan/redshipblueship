/** The assumed set / bag element: an origin-tagged item plus the class it was
 *  admitted under. The class is CARRIED, not filtered on — see the fill. */
typedef struct {
    SharedItem item;    // originGame must be GAME_OOT or GAME_MM
    uint16_t itemClass; // one RSBS_ITEMCLASS_* bit, or 0 when the caller has none
} ComboLogicBagItem;

typedef struct {
    const ComboLogicBagItem* assumed; // the assumed set A; NULL iff assumedCount == 0
    int assumedCount;
    uint8_t goal; // RSBS_COMBO_GOAL_*
} ComboLogicRoundRequest;

typedef struct {
    int status;     // RSBS_COMBO_LOGIC_*
    int iterations; // inner alternations actually run
    int crossingOpenOoT;
    int crossingOpenMM;
    int goalOoT;        // the OoT half's own answer
    int goalMM;         // the MM half's, AFTER the arrival gate
    int goalExpression; // GOAL(goalOoT, goalMM); -1 when the goal has no evaluator
    int candidatesOoT;  // reached, coordinator-unassigned hosts
    int candidatesMM;   // ditto, and zero while the arrival gate is closed
    int exchanged;      // crossing exchanges performed this round
    /** Was every host the coordinator has already placed on reached in this
     *  round? 1 yes, 0 no, and -1 when the round did not get far enough to
     *  evaluate it (an engine refusal or a malformed request). It is evaluated
     *  INSIDE the round because `checkReached` is only valid before teardown —
     *  which is why the `all-reachable` rung cannot be a post-pass. */
    int allHostsReached;
} ComboLogicRoundResult;

/**
 * Run ONE round and report what it saw, leaving the placement tables untouched.
 *
 * This is the coordinator's smallest observable unit and it is public for two
 * reasons beyond the locks: epic #645's first work item is measuring the cost
 * of one linked round against the #582 creation budget, and its second is
 * whether an assumed fill over MM's forward-authored graph converges — both are
 * questions about this function.
 *
 * @return the status, also written to `out->status` when `out` is non-NULL.
 */
int Combo_Logic_RunRound(const ComboLogicRoundRequest* req, ComboLogicRoundResult* out);

// ============================================================================
// THE SINGLE-BAG ASSUMED FILL
// ============================================================================

typedef struct {
    const ComboLogicBagItem* bag; // the union bag; NULL iff bagCount == 0
    int bagCount;
    uint8_t goal;      // RSBS_COMBO_GOAL_*  } both from the FROZEN record,
    uint8_t logicRung; // RSBS_COMBO_RUNG_*  } never from a live CVar
    /**
     * The coordinator's PRIVATE RNG seed, derived by the caller from the frozen
     * identity (`gComboCtx.sharedRandoSeed`, `comboSettingsHash`, ...). It is
     * never a game's RNG: both engines' RNGs belong to their own fills, a query
     * must consume none, and a coordinator that drew from either would couple
     * the world to the number of rounds the search happened to run.
     */
    uint32_t seed;
    /** Batch roll-backs within this seed; 0 means RSBS_COMBO_LOGIC_FILL_RETRIES.
     *  Re-rolling the SEED is the attempt ladder's job, one level up. */
    int maxAttempts;
} ComboLogicFillRequest;

typedef struct {
    int status;
    int attempts;         // attempts consumed, including the successful one
    int placed;           // placements in the tables on return
    int rounds;           // rounds run across every attempt
    bool goalProven;      // the exit condition was evaluated and held
    bool proofSkipped;    // rung `none`: no proof was attempted (goalProven is false)
    bool allHostsReached; // rung `all-reachable` only: every placed host was reached
    uint32_t placementDigest;
} ComboLogicFillResult;

/**
 * THE FILL. One bag, both games' hosts, the GOAL expression as the exit
 * condition (ADR 0010 D3/D4, increment 3).
 *
 * The algorithm, which is OoT's own assumed fill lifted one level (audit §4.3):
 * shuffle the bag with the private RNG; for each item, run a round with every
 * OTHER unplaced bag item assumed, take the union of both sides' candidate
 * hosts, pick one uniformly, and place it on its owning side. On an empty
 * candidate set, roll the whole batch back and retry with a different
 * deterministic order. When the bag is empty, run one final round with NOTHING
 * assumed and require the GOAL expression — that requirement is the loop's exit
 * condition, never a check bolted on after it.
 *
 * THE RUNGS ARE ONE CODE PATH with the exit condition parametrized, which is
 * ADR 0010 D5 read literally — the operator's "bag, then randomly distribute"
 * base mode is this same fill:
 *   RSBS_COMBO_RUNG_NONE          - the final round is SKIPPED. Placement still
 *                                   happens through the rounds (so a `none`
 *                                   world is still a legal single-bag world),
 *                                   but nothing is proved: `proofSkipped` is
 *                                   true and `goalProven` is false. A caller
 *                                   must not read "not proven" as "failed".
 *   RSBS_COMBO_RUNG_BEATABLE      - the GOAL expression must hold.
 *   RSBS_COMBO_RUNG_ALL_REACHABLE - the GOAL expression must hold AND every
 *                                   host the COMBO FILL placed on must be
 *                                   reached in that final round.
 *
 * The all-reachable rung's obligation is deliberately over PLACED hosts and not
 * over every location in either world. "Every location reachable" is each half's
 * own existing strictness axis (`RSK_ALL_LOCATIONS_REACHABLE` and MM's
 * analogue), which ADR 0010 §1.2 explicitly keeps per-half and composes with any
 * GOAL; the pair-level obligation this rung adds on top is that nothing the
 * SINGLE BAG distributed ended up somewhere the player cannot stand. Widening it
 * would also need a vtable call that enumerates every shuffled host, which no
 * consumer has asked for.
 *
 * DETERMINISM: the whole result is a pure function of (`bag` contents and
 * order, `goal`, `logicRung`, `seed`, `maxAttempts`, the two registered
 * engines). Same inputs, same placements, byte for byte.
 *
 * ON FAILURE the placement tables hold the LAST attempt's partial state; a
 * caller that means to discard them calls Combo_Logic_ResetPlacements().
 *
 * @return the status, also written to `out->status` when `out` is non-NULL.
 */
int Combo_Logic_RunFill(const ComboLogicFillRequest* req, ComboLogicFillResult* out);

