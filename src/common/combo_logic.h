/**
 * @file combo_logic.h
 * @brief The combo-logic coordinator and the engine query surface it drives
 *        (ADR 0010 increment 3, #645; O4 = COMPOSITION, operator 2026-09-17).
 *
 * ============================================================================
 * WHAT THIS IS, AND WHAT IT IS NOT
 * ============================================================================
 *
 * ADR 0010 answer O4 is ruled COMPOSITION: both ports' solvers stay
 * authoritative in their own dialects, and a game-header-free coordinator in
 * `src/common` owns exactly three things — the union bag of origin-tagged
 * items, the two origin-keyed placement tables, and the round loop. It never
 * evaluates a guard, never names an `RG_*` / `RI_*` / `RR_*` / `RC_*`, and
 * never touches a save. Everything that requires a game's enum in scope lives
 * behind the `ComboLogicEngine` vtable below, implemented in that game's own
 * single-exe TU beside its foreign-items TU.
 *
 * NOTHING HERE IS WIRED INTO A PRODUCTION PATH. No engine is registered by any
 * shipping TU at this commit; no creation seam calls the fill; no world is
 * generated by this code. It is the coordinator core plus its contract, locked
 * over synthetic stub engines in `src/common/tests/test_combo_logic.c`. The
 * deliberate absences are listed at the bottom of this header — read that list
 * before concluding something is missing by accident.
 *
 * ============================================================================
 * WHY A REGISTERED VTABLE AND NOT FIXED `extern "C"` SYMBOLS
 * ============================================================================
 *
 * The solver-inventory audit (§4.1) sketched the surface as two sets of fixed
 * C symbols (`OoT_Logic_Expand`, `MM_Logic_Expand`, ...). A REGISTERED VTABLE
 * IS REQUIRED INSTEAD, for one reason that decides it:
 *
 *   A ROM-free, display-free test must be able to drive the whole coordinator
 *   over engines it authors itself.
 *
 * Fixed symbols cannot be substituted: the real engines' TUs link into the same
 * binary as the tests (this is a single executable), so a test cannot provide
 * its own `OoT_Logic_Expand` without a duplicate-symbol error, and a test that
 * drove the REAL engines would need both ROMs, both graphs built, a display for
 * MM's crawl (audit §6.3), and a generated world — which is precisely the
 * dependency chain that has kept every pair-level assertion in this project
 * vacuous. With a vtable, `test_combo_logic.c` registers two small stub engines
 * whose reachability is a bitmask, and every claim below is falsifiable on the
 * `redship` tier in milliseconds.
 *
 * Two smaller reasons, both real: a build with only one game's engine TU linked
 * resolves cleanly (the missing origin simply has no engine, the same property
 * `Combo_RegisterForeignItemPool` exists for), and MM's snapshot/restore pair is
 * OPTIONAL, which a fixed-symbol surface can only express as a stub that lies.
 *
 * The cost is one indirect call per query, against an engine call that runs a
 * whole reachability search. It is not measurable.
 *
 * ============================================================================
 * THE BOUNDARY (ADR 0002)
 * ============================================================================
 *
 * Only game-neutral scalars cross: a `SharedItem` (origin tag + id), a HOST
 * CHECK ID, and the HOST'S ORIGIN GAME. Nothing else. `assumeOwnItem` and the
 * own-origin half of `place` receive ONLY ids from the receiving engine's own
 * id-space, because the coordinator routes by `item.originGame` before calling —
 * so ADR 0002 holds by construction, not by review. MM reports "check 201
 * reached"; the coordinator looks up `placement[MM][201] == SharedItem{OOT, id}`
 * and calls the OoT engine's `assumeOwnItem(id)`. No MM code ever sees that id.
 *
 * Host check ids live in each game's own check id-space and are never compared
 * across games: `(hostGame, hostCheck)` is the key, exactly as `(originGame,
 * name)` is the key in foreign_items.h for the same #356 reason.
 */

